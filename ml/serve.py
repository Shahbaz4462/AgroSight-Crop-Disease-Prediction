"""AgroSight inference API.

Run:  uvicorn serve:app --host 0.0.0.0 --port 8000
Contract (matches src/services/ai/modelApiService.ts):
  POST /predict  multipart/form-data { file: image }
  -> { crop, disease, confidence, status, alternatives:[{crop,disease,confidence}], model }
Advice text (symptoms, treatment) is attached by the front end from the curated knowledge base,
never generated by the model.
"""
import io
import json
from pathlib import Path

import torch
import torch.nn as nn
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from PIL import Image, ImageOps
from torchvision import models, transforms

ROOT = Path(__file__).parent
ART = ROOT / "artifacts"
SIZE = 224
MEAN, STD = [0.485, 0.456, 0.406], [0.229, 0.224, 0.225]

# Below this top-1 probability we refuse to name a disease.
CONFIDENCE_GATE = 0.60
# If the top two classes are this close, the model is torn between them: call it uncertain.
MIN_MARGIN = 0.15

classes = json.loads((ART / "classes.json").read_text())
model = models.mobilenet_v3_large(weights=None)
model.classifier[-1] = nn.Linear(model.classifier[-1].in_features, len(classes))
model.load_state_dict(torch.load(ART / "model.pt", map_location="cpu"))
model.eval()

tf = transforms.Compose([
    transforms.Resize(int(SIZE * 1.14)),
    transforms.CenterCrop(SIZE),
    transforms.ToTensor(),
    transforms.Normalize(MEAN, STD),
])


CROP_TIDY = {"Corn maize": "Corn", "Pepper bell": "Pepper", "Cherry including sour": "Cherry", "Orange": "Citrus"}
DISEASE_TIDY = {
    "Cercospora leaf spot Gray leaf spot": "Gray Leaf Spot",
    "Esca Black Measles": "Esca (Black Measles)",
    "Leaf blight Isariopsis Leaf Spot": "Leaf Blight",
    "Haunglongbing Citrus greening": "Citrus Greening",
    "Spider mites Two spotted spider mite": "Spider Mites",
    "Tomato Yellow Leaf Curl Virus": "Yellow Leaf Curl Virus",
    "Tomato mosaic virus": "Mosaic Virus",
}


def split_label(label: str):
    crop, _, disease = label.partition("___")
    crop = " ".join(crop.replace("_", " ").split())
    disease = " ".join(disease.replace("_", " ").split()) or "healthy"
    crop = CROP_TIDY.get(crop, crop)
    disease = DISEASE_TIDY.get(disease, disease)
    if disease.lower() != "healthy":
        disease = disease[0].upper() + disease[1:]
    return crop, disease


app = FastAPI(title="AgroSight inference")
app.add_middleware(CORSMiddleware, allow_origins=["*"], allow_methods=["*"], allow_headers=["*"])


@app.get("/health")
def health():
    return {"ok": True, "classes": len(classes)}


@app.post("/predict")
async def predict(file: UploadFile = File(...)):
    try:
        img = ImageOps.exif_transpose(Image.open(io.BytesIO(await file.read()))).convert("RGB")
    except Exception:
        raise HTTPException(400, "Could not read the image")
    with torch.no_grad():
        probs = torch.softmax(model(tf(img).unsqueeze(0)), 1)[0]
    top = torch.topk(probs, 3)
    p1, p2 = top.values[0].item(), top.values[1].item()
    crop, disease = split_label(classes[top.indices[0].item()])
    healthy = disease.lower() == "healthy"
    if p1 < CONFIDENCE_GATE or (p1 - p2) < MIN_MARGIN:
        status = "uncertain"
    else:
        status = "healthy" if healthy else "diseased"
    return {
        "crop": crop,
        "disease": "Healthy" if healthy else disease,
        "confidence": round(p1 * 100, 1),
        "status": status,
        "alternatives": [
            {"crop": c, "disease": d, "confidence": round(v.item() * 100, 1)}
            for v, i in zip(top.values, top.indices)
            for c, d in [split_label(classes[i.item()])]
        ],
        "model": "mobilenetv3-large / plantvillage+cotton v1",
    }
