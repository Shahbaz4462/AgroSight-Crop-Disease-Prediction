"""Generate src/data/pakistanBoundaries.ts from a downloaded geoBoundaries file.

Usage: python3 scripts/generate_pakistan_boundaries.py geoBoundaries-PAK-ADM1_simplified.geojson

Input: geoBoundaries gbOpen, Pakistan ADM1 (simplified) GeoJSON.
Output: src/data/pakistanBoundaries.ts with only shapeName + simplified
coordinates (4 decimal places, Douglas-Peucker tolerance 0.01 degrees),
so the file stays small enough for the frontend bundle.
No coordinates are invented here — every point comes from the input file.
"""
import json, math, sys
from pathlib import Path

def simplify(pts, tol):
    # Douglas-Peucker, iterative, keeps first/last points.
    if len(pts) <= 2:
        return pts
    keep = [False]*len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts)-1)]
    while stack:
        a, b = stack.pop()
        if b <= a+1:
            continue
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx-ax, by-ay
        norm = math.hypot(dx, dy) or 1.0
        far, idx = 0.0, -1
        for i in range(a+1, b):
            d = abs((pts[i][0]-ax)*dy - (pts[i][1]-ay)*dx) / norm
            if d > far:
                far, idx = d, i
        if far > tol:
            keep[idx] = True
            stack.append((a, idx)); stack.append((idx, b))
    return [p for p, k in zip(pts, keep) if k]

def main():
    src = Path(sys.argv[1])
    data = json.loads(src.read_text())
    features = []
    for feat in data["features"]:
        geom = feat["geometry"]
        polys = []
        if geom["type"] == "Polygon":
            polys = [geom["coordinates"]]
        elif geom["type"] == "MultiPolygon":
            polys = geom["coordinates"]
        else:
            continue
        out_polys = []
        for poly in polys:
            out_rings = []
            for ring in poly:
                pts = [[round(lon, 4), round(lat, 4)] for lon, lat in ring]
                # Rings are closed (first point == last point). Simplify the
                # open ring, then re-close it, or Douglas-Peucker sees a
                # zero-length baseline and drops every point.
                closed = len(pts) > 1 and pts[0] == pts[-1]
                core = pts[:-1] if closed else pts
                core = simplify(core, 0.01)
                if closed:
                    core = core + [core[0]]
                out_rings.append(core)
            out_polys.append(out_rings)
        features.append({
            "type": "Feature",
            "properties": {"shapeName": feat["properties"]["shapeName"]},
            "geometry": {"type": "MultiPolygon", "coordinates": out_polys},
        })
    names = [f["properties"]["shapeName"] for f in features]
    print("features:", len(features), names)
    out = Path(__file__).resolve().parent.parent / "src/data/pakistanBoundaries.ts"
    body = json.dumps({"type": "FeatureCollection", "features": features}, separators=(",", ":"))
    out.write_text(
        "// Real provincial boundaries for the disease map.\n"
        "// Source: geoBoundaries gbOpen, Pakistan ADM1 (simplified),\n"
        "// https://www.geoboundaries.org — generated by\n"
        "// scripts/generate_pakistan_boundaries.py, coordinates rounded\n"
        "// to 4 decimals and simplified (tolerance 0.01 degrees).\n"
        "// No boundary was drawn by hand; every point comes from that file.\n"
        f"export const PAKISTAN_BOUNDARIES = {body} as const;\n"
    )
    print("wrote", out, out.stat().st_size, "bytes")

if __name__ == "__main__":
    main()
